export type EnterpriseLabels = typeof en;
export function enterpriseCopy(ctx: ClientContext): EnterpriseLabels {
  return language(ctx) === "zh" ? zh : en;
}
export function enterpriseLabels(ctx: ClientContext) {
  return {
    getSnapshot: () => enterpriseCopy(ctx),
    subscribe: (listener: () => void) => ctx.locale.subscribe(listener),
  };
}
/** Fill `{name}` placeholders in a localized label. */
export function format(
  label: string,
  values: Record<string, string | number>,
): string {
  return label.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in values ? String(values[key]) : match,
  );
}
export function enterpriseError(code: string, t: EnterpriseLabels, fallback = t.operationFailed): string {
  const diagnostic = /^[A-Z][A-Z0-9_]{0,79}$/.test(code) ? ` (${code})` : '';
  if (code === 'IPW_ACCOUNT_UNAVAILABLE') return t.accountUnavailable + diagnostic;
  if (code === 'IPW_ACCOUNT_TIMEOUT') return t.accountTimeout + diagnostic;
  if (code === 'IPW_HOST_UNAVAILABLE') return t.hostUnavailable + diagnostic;
  if (['SERVICE_BUSY', 'SERVICE_QUEUE_TIMEOUT', 'RATE_LIMITED', 'TOO_MANY_REQUESTS'].includes(code)) return t.serviceBusy + diagnostic;
  if (code === 'SERVICE_DRAINING') return t.serviceRestarting + diagnostic;
  if (code === 'DATABASE_UNAVAILABLE') return t.databaseUnavailable + diagnostic;
  if (['IPW_INVALID_RESPONSE', 'IPW_RESPONSE_TOO_LARGE'].includes(code)) return t.invalidResponse + diagnostic;
  if (['INVALID_INPUT', 'INVALID_JSON', 'IPW_INVALID_INPUT'].includes(code)) return t.invalidRequest + diagnostic;
  if (['INTERNAL_ERROR', 'IPW_SERVICE_UNAVAILABLE'].includes(code)) return t.internalFailure + diagnostic;
  if (code === 'IPW_ACCOUNT_CHANGED') return t.accountChanged;
  if (code === "PUBLICATION_VERSION_INVALID" || code === "IPW_DSH_PINNED_PLUGIN_REQUIRED") return t.publicationVersionInvalid;
  if (code === 'PUBLICATION_VERSION_LABEL_INVALID') return t.publicationVersionLabelInvalid;
  if (code === 'SKILL_FILE_TYPE_INVALID') return t.skillFileTypeInvalid;
  if (code === 'SKILL_FILE_TOO_LARGE') return t.skillFileTooLarge;
  if (code === 'SKILL_FILE_ENCODING_INVALID') return t.skillFileEncodingInvalid;
  if (code === 'SKILL_FILE_EMPTY') return t.skillFileEmpty;
  if (code === "PUBLICATION_TITLE_REQUIRED") return t.publicationTitleRequired;
  if (code === "PUBLICATION_DESCRIPTION_REQUIRED") return t.publicationDescriptionRequired;
  if (code === "PUBLICATION_VERSION_EXISTS") return t.publicationVersionExists;
  if (code === "PUBLICATION_EXISTS") return t.publicationExists;
  if (code === "PUBLICATION_PACKAGE_MISMATCH") return t.publicationPackageMismatch;
  if(['IPW_CLOUD_DISABLED','CLOUD_DISABLED'].includes(code))return t.cloudDisabled;
  if(['IPW_CLOUD_START_FAILED','CLOUD_START_FAILED'].includes(code))return t.cloudFailed;
  if(code==='CLOUD_PROJECT_BUSY')return t.cloudBusy;
  if (["IPW_SIGN_IN_REQUIRED", "SIGN_IN_REQUIRED"].includes(code))
    return t.signInRequired;
  if (
    ["ENTERPRISE_FORBIDDEN", "SHARE_FORBIDDEN", "RESOURCE_FORBIDDEN"].includes(
      code,
    )
  )
    return t.forbidden;
  if (code === "EMAIL_NOT_VERIFIED") return t.verifyEmail;
  if (code === "MEMBER_SUSPENDED") return t.memberSuspendedHint;
  if (code === "INVITATION_USED") return t.inviteUsed;
  if (code === "INVITATION_NOT_EDITABLE") return t.inviteNotEditable;
  if (code === "INVITATION_EMPLOYEE_NUMBER_IN_USE") return t.employeeNumberInUse;
  if (
    [
      "INVITATION_EXPIRED",
      "INVITATION_EMAIL_MISMATCH",
      "IPW_INVALID_INVITATION",
    ].includes(code)
  )
    return t.invalidInvite;
  if (code === "RECIPIENT_NOT_FOUND" || code === "SHARE_RECIPIENT_INVALID") return t.recipientMissing;
  if (code === "SHARE_NOT_FOUND") return t.missingShare;
  if (code === "IPW_SHARE_EMPTY") return t.emptyShare;
  if (code === "IPW_SHARE_WORKSPACE_REQUIRED") return t.copyWorkspaceRequired;
  if (code === "IPW_SHARE_TOO_LARGE") return t.tooLarge;
  if (code === "IPW_PROJECT_NOT_FOUND") return t.projectMissing;
  if (
    [
      "WORK_VERSION_CONFLICT",
      "PROJECT_VERSION_CONFLICT",
      "FILE_VERSION_CONFLICT",
    ].includes(code)
  )
    return t.versionConflict;
  if (code === "IPW_NO_RESULT") return t.noGeneratedResult;
  if (code === "IPW_CONTINUATION_BLOCKED") return t.continuationBlocked;
  if (["WORK_FORBIDDEN", "PROJECT_FORBIDDEN"].includes(code))
    return t.forbidden;
  if (code === "WORK_NOT_FOUND") return t.projectMissing;
  if (code === "IPW_SHARE_CHANGED") return t.changed;
  if (code === "IPW_ENTERPRISE_MCP_UNAVAILABLE") return t.mcpUnavailable;
  if (code === "MCP_REVIEW_REQUIRED") return t.mcpReviewRequired;
  if (code === "IPW_PUBLIC_MCP_UNAVAILABLE") return t.publicMcpUnavailable;
  if (code === "IPW_ENTERPRISE_SETTINGS_UNAVAILABLE") return t.settingsUnavailable;
  if (code === "IPW_ENTERPRISE_CAPABILITIES_UNAVAILABLE") return t.organizationCapabilitiesUnavailable;
  if (code === "IPW_INVITATION_SERVICE_MISMATCH") return t.invitationServiceMismatch;
  if (code === "DEPARTMENT_CYCLE") return t.departmentCycle;
  return fallback + diagnostic;
}
