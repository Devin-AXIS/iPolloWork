export type EnterpriseLabels = typeof en;
export function enterpriseCopy(ctx: ClientContext): EnterpriseLabels {
  return language(ctx) === "zh" ? zh : en;
}
export function enterpriseLabels(ctx: ClientContext) {
  return {
    getSnapshot: () => enterpriseCopy(ctx),
    subscribe: (listener: () => void) => ctx.locale.subscribe(listener),
  };
}
/** Fill `{name}` placeholders in a localized label. */
export function format(
  label: string,
  values: Record<string, string | number>,
): string {
  return label.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in values ? String(values[key]) : match,
  );
}
export function enterpriseError(code: string, t: EnterpriseLabels): string {
  if (["IPW_SIGN_IN_REQUIRED", "SIGN_IN_REQUIRED"].includes(code))
    return t.signInRequired;
  if (
    ["ENTERPRISE_FORBIDDEN", "SHARE_FORBIDDEN", "RESOURCE_FORBIDDEN"].includes(
      code,
    )
  )
    return t.forbidden;
  if (code === "EMAIL_NOT_VERIFIED") return t.verifyEmail;
  if (
    [
      "INVITATION_EXPIRED",
      "INVITATION_EMAIL_MISMATCH",
      "IPW_INVALID_INVITATION",
    ].includes(code)
  )
    return t.invalidInvite;
  if (code === "RECIPIENT_NOT_FOUND") return t.recipientMissing;
  if (code === "IPW_SHARE_TOO_LARGE") return t.tooLarge;
  if (code === "IPW_PROJECT_NOT_FOUND") return t.projectMissing;
  if (
    [
      "WORK_VERSION_CONFLICT",
      "PROJECT_VERSION_CONFLICT",
      "FILE_VERSION_CONFLICT",
    ].includes(code)
  )
    return t.versionConflict;
  if (code === "IPW_NO_RESULT") return t.noGeneratedResult;
  if (code === "IPW_CONTINUATION_BLOCKED") return t.continuationBlocked;
  if (["WORK_FORBIDDEN", "PROJECT_FORBIDDEN"].includes(code))
    return t.forbidden;
  if (code === "WORK_NOT_FOUND") return t.projectMissing;
  if (code === "IPW_SHARE_CHANGED") return t.changed;
  return t.operationFailed;
}
