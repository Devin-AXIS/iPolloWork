export function dataCopy(ctx: ClientContext): DataLabels {
  return language(ctx) === 'zh' ? zh : en
}
/** A label store that follows the DSH locale. */
export function dataLabels(ctx: ClientContext) {
  return { getSnapshot: () => dataCopy(ctx), subscribe: (listener: () => void) => ctx.locale.subscribe(listener) }
}
